"""Gate 5: the active present is grazed by a *belief over* slow operators.

A cue is a partial observation of a trace generated by one remembered dynamic.
A learned sensor-selection policy chooses which parts to inspect. Unlike
Gate 3/4, the current recurrent state is never erased or replaced by a recall.

The memory identity is NEVER available to the querying policy, although an
outcome label is provided after each training trial for reinforcement learning.
This toy is not a model of apical dendrites, selfhood or phenomenology.
"""
from __future__ import annotations
from dataclasses import dataclass
import numpy as np
from structural_memory import unit


@dataclass(frozen=True)
class LensProtocol:
    dim: int = 8
    channels: int = 6
    probe_budget: int = 3
    noise: float = .10
    rho: float = .13
    train_trials: int = 2600
    test_trials: int = 350
    seed: int = 19


class ContinuingPresent:
    """One recurrent state across episodes, with bounded memory influence."""
    def __init__(self, base: np.ndarray, rho: float = .13, seed: int = 19):
        self.base = np.asarray(base, dtype=float)
        self.rho = float(rho)
        if not 0 <= rho <= .5:
            raise ValueError('rho must be in [0, 0.5]')
        self.state = unit(np.random.default_rng(seed).normal(size=self.base.shape[0]))
        self.steps = 0
        self.autonomous_updates = 0
        self.resets = 0
        self.max_relative_graze = 0.0

    def advance(self, elapsed: float) -> np.ndarray:
        """Exact real-time autonomous rotation/ringdown, even with no observations."""
        if not np.isfinite(elapsed) or elapsed < 0:
            raise ValueError('elapsed time must be nonnegative and finite')
        v=self.state.reshape(-1,2)
        w=np.linspace(.25,.90,len(v)) * elapsed
        c,s=np.cos(w),np.sin(w)
        rotated=np.stack((c*v[:,0]-s*v[:,1],s*v[:,0]+c*v[:,1]),axis=-1)
        self.state=np.exp(-elapsed/50.)*rotated.reshape(-1)
        self.autonomous_updates+=1
        return self.state.copy()

    def step(self, external: np.ndarray, ops: np.ndarray, posterior: np.ndarray, couple=True):
        z = self.state.copy()
        # The ongoing process includes a nearly unitary rotation and new input.
        baseline = 0.95*(self.base / .78)@z + .18*unit(external)
        deviations = np.einsum('s,sij,j->i', posterior, ops-self.base, z)
        # A graze changes the direction but never loads a saved full state.
        delta = self.rho*deviations if couple else np.zeros_like(z)
        # Bounded per-step feedback, even for unstable stored operators.
        cap = .15*max(float(np.linalg.norm(baseline)),1e-12)
        if np.linalg.norm(delta)>cap:
            delta *= cap / np.linalg.norm(delta)
        self.max_relative_graze = max(self.max_relative_graze,
            float(np.linalg.norm(delta))/max(float(np.linalg.norm(baseline)),1e-12))
        self.state = baseline+delta
        self.steps += 1
        return self.state.copy(),baseline.copy()


def sensing_axes(dim:int, channels:int, seed:int):
    if channels<2 or channels>dim:
        raise ValueError('channels must be in [2,dim]')
    q,_=np.linalg.qr(np.random.default_rng(seed).normal(size=(dim,dim)))
    return q[:,:channels].T


def predictions(ops: np.ndarray, trigger: np.ndarray, axes: np.ndarray):
    """Expected scalar cue response for every memory and available attention axis."""
    return (np.einsum('sij,j->si',ops,trigger)) @ axes.T


def observe_fragment(true_op:np.ndarray, trigger:np.ndarray, axes:np.ndarray,
                     noise:float, rng:np.random.Generator):
    return axes@(true_op@trigger)+rng.normal(scale=noise,size=len(axes))


def bayes_update(prior:np.ndarray, expected:np.ndarray, y:float, noise:float):
    if noise<=0:raise ValueError('noise >0 required')
    logits=np.log(np.maximum(prior,1e-100))-.5*((expected-y)/noise)**2
    logits-=np.max(logits)
    post=np.exp(logits)
    return post/post.sum()


def entropy(p):
    p=np.maximum(p,1e-12)
    return float(-np.sum(p*np.log(p))/np.log(len(p)))


class LensPolicy:
    """Small experiential REINFORCE controller; no oracle action labels.

    Scores a limited set of scalar attention channels and STOP from observable
    posterior/teacher-prediction features. Parameters updated only after a
    training trial ends and its correct source is revealed by the environment.
    No secret source identifier is used at decision time.
    """
    features_dim=10
    def __init__(self, channels:int, seed:int=0):
        self.channels=channels
        self.theta=np.zeros(self.features_dim)
        self.bias=np.zeros(channels+1)
        self.rng=np.random.default_rng(seed)
        self.reward_baseline=0.
        self.training_steps=0

    @property
    def scalar_budget(self):
        return len(self.theta)+len(self.bias)+1

    def features(self,p:np.ndarray,mu:np.ndarray,used:set[int],step:int,noise:float):
        out=np.zeros((self.channels+1,self.features_dim))
        H=entropy(p)
        for j in range(self.channels):
            pred=mu[:,j]
            avg=np.dot(p,pred)
            variance=float(np.dot(p,(pred-avg)**2))/noise**2
            gap=float(np.ptp(pred))/noise
            out[j]=[1.,min(variance,8.)/8.,min(gap,8.)/8.,H,
                    float(p.max()),step/3.,float(j in used),0.,0.,0.]
        out[-1]=[1.,0.,0.,H,float(p.max()),step/3.,0.,1.,
                 float(p.max()>.8),float(p.max()>.95)]
        return out

    def probs(self,p,mu,used,step,noise,greedy=False,temperature=1.):
        feat=self.features(p,mu,used,step,noise)
        logits=feat@self.theta+self.bias
        # Repeating the exact same channel is strictly wasted with a fixed fragment.
        if used:logits[list(used)]=-1e9
        # A zero-measurement stop is permitted and is a meaningful baseline.
        logits-=np.max(logits)
        probs=np.exp(logits/max(temperature,1e-5));probs/=probs.sum()
        return probs,feat

    def query(self,mu:np.ndarray,observed:np.ndarray,noise:float,budget:int,
              mode:str='sample',train:bool=False,cost:float=.08,lr:float=.035,
              source:int|None=None):
        p=np.ones(mu.shape[0])/mu.shape[0]
        used=set()
        steps=[]
        for t in range(budget):
            probs,feat=self.probs(p,mu,used,t,noise)
            if mode=='greedy':action=int(np.argmax(probs))
            elif mode=='sample':action=int(self.rng.choice(len(probs),p=probs))
            else:raise ValueError('mode must be greedy/sample')
            steps.append((action,probs,feat))
            if action==self.channels:break
            used.add(action)
            p=bayes_update(p,mu[:,action],float(observed[action]),noise)
        n=len(used)
        if train:
            if source is None:raise ValueError('training needs retrospective outcome')
            # Proper log score of posterior, minus observation cost.
            reward=float(np.log(max(p[source],1e-8))-cost*n)
            self.reward_baseline+=.008*(reward-self.reward_baseline)
            advantage=np.clip(reward-self.reward_baseline,-6.,6.)
            for action,probs,feat in steps:
                # dlog pi(action) / d(theta,bias)
                gradfeat=feat[action]-probs@feat
                self.theta+=lr*advantage*gradfeat
                one=np.zeros(len(probs));one[action]=1
                self.bias+=lr*advantage*(one-probs)
            self.theta=np.clip(self.theta,-6,6)
            self.bias=np.clip(self.bias,-6,6)
            self.training_steps+=1
        return p,n,[s[0] for s in steps]


def fixed_query(mu,observed,noise,budget,method='best'):
    """Strong unlearned controls over same discrete attention channels."""
    p=np.ones(len(mu))/len(mu)
    rng=None
    if method=='none':return p,0,[]
    actions=[]
    for t in range(budget):
        if method=='best':
            variances=np.array([float(np.dot(p,(mu[:,j]-p@mu[:,j])**2))
                        for j in range(mu.shape[1])])
            variances[actions]=-1
            j=int(np.argmax(variances))
        elif method=='first':j=next(k for k in range(mu.shape[1]) if k not in actions)
        else:raise ValueError('invalid baseline')
        p=bayes_update(p,mu[:,j],observed[j],noise)
        actions.append(j)
    return p,len(actions),actions
